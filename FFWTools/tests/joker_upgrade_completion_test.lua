package.path='FFWTools/src/FFWJokerInfo/Scripts/?.lua;'..package.path
local E,C=require('Effects'),require('Cards')
local cases,checks,failed=0,0,0
local function eq(a,b,m) checks=checks+1;assert(a==b,(m or '')..' expected '..tostring(b)..', got '..tostring(a)) end
local function near(a,b,m) checks=checks+1;assert(type(a)=='number' and math.abs(a-b)<1e-6,(m or '')..' expected '..tostring(b)..', got '..tostring(a)) end
local function val(r,key) assert(r.metrics[key],'missing upgrade metric '..key);return r.metrics[key].value end
local function test(name,fn) cases=cases+1;local ok,err=pcall(fn);if ok then print('PASS '..name) else failed=failed+1;print('FAIL '..name..': '..tostring(err)) end end
local function ammo(counts,item)
    assert(type(E.initialAmmoCapacities)=='function','missing verified ammo initialization calculator')
    return E.initialAmmoCapacities(counts,{itemName=item})
end

test('ClipSize rounds each accumulated upgrade contribution against the real weapon base',function()
    local p=E.preview('jokerUpgradeClipSize',{jokerUpgradeClipSize=1},{itemName='itemPistol',itemCounts={},heroCounts={}})
    near(val(p.current,'magazineCapacity'),7)
    near(val(p.after,'magazineCapacity'),7,'1.2 bonus rounds to one instead of rounding each level')
    near(val(E.evaluate('jokerUpgradeClipSize',3,{itemName='itemPistol'}),'magazineCapacity'),8)
    near(val(E.evaluate('jokerUpgradeClipSize',1,{itemName='itemLongRanger'}),'magazineCapacity'),8)
end)
test('Ammo initialization rounds distinct sources separately before adding them',function()
    local a=ammo({jokerUpgradeTotalAmmoBag=1,jokerUpgradeTotalAmmoBagC=1},'itemBow')
    near(a.reserve,34,'30 + round(1.5) + round(1.5), not round(33)')
    near(a.magazine,1)
    a=ammo({jokerUpgradeTotalAmmoBag=1,jokerSpareBullets=1,jokerUpgradeClipSize=1},'itemPistol')
    near(a.reserve,69)
    near(a.magazine,7)
end)
test('Ammo respects every relevant whitelist and fixed-count weapon exception',function()
    local counts={jokerUpgradeClipSize=100,jokerUpgradeTotalAmmoBag=1,jokerUpgradeTotalAmmoBagC=2,jokerSpareBullets=1}
    local a=ammo(counts,'itemMinigun')
    near(a.magazine,300,'ClipSize does not apply to Minigun')
    near(a.reserve,375)
    for _,item in ipairs({'itemBanjo','itemKnuckles','itemLasso'}) do
        a=ammo(counts,item);near(a.magazine,1);near(a.reserve,1)
    end
    eq(ammo(counts,'itemUnknown').known,false)
end)
test('Hero ammo bag uses the actual selected ammo weapon instead of a fictional hero magazine',function()
    local p=E.preview('jokerUpgradeTotalAmmoBag',{jokerUpgradeTotalAmmoBag=1},
        {itemName='itemHero',heldItemName='itemBow',heldItemCounts={jokerUpgradeTotalAmmoBagC=1},heroCounts={}})
    near(val(p.current,'reserveCapacity'),34)
    near(val(p.after,'reserveCapacity'),35)
    eq(val(E.evaluate('jokerUpgradeTotalAmmoBag',2,{itemName='itemHero'}),'reserveCapacity'),nil)
end)
test('BagC uses actual reserve bases and remains a runtime level beyond the hall metadata',function()
    near(val(E.evaluate('jokerUpgradeTotalAmmoBagC',1,{itemName='itemDualRevolver'}),'reserveCapacity'),101)
    near(val(E.evaluate('jokerUpgradeTotalAmmoBagC',2,{itemName='itemMinigun'}),'reserveCapacity'),330)
    near(val(E.evaluate('jokerUpgradeTotalAmmoBagC',20,{itemName='itemBow'}),'reserveCapacity'),60)
end)
test('Empty availableOnItems makes BagB and ShieldPoints inactive even when supplied a nonzero level',function()
    local bag=E.evaluate('jokerUpgradeTotalAmmoBagB',10,{itemName='itemPistol'})
    near(val(bag,'reserveCapacityBonus'),0)
    eq(val(bag,'applicable'),false)
    local shield=E.evaluate('jokerUpgradeShieldPoints',8,{})
    near(val(shield,'maxShield'),100,'retain old metric name but correct the empty whitelist')
    eq(val(shield,'applicable'),false)
    eq(E.rule('jokerUpgradeShieldPoints').status,'verified')
    eq(E.rule('jokerUpgradeTotalAmmoBagB').note:find('适用列表为空',1,true)~=nil,true)
end)
test('Jetpack fuel rounds first and its child initialization copies reserve into starting fuel',function()
    local p=E.preview('jokerUpgradeJetpackFuel',{jokerUpgradeJetpackFuel=1},
        {itemName='itemJetpack',itemCounts={},heroCounts={}})
    near(val(p.current,'fuelCapacity'),8)
    near(val(p.after,'fuelCapacity'),9)
    local a=ammo({jokerUpgradeJetpackFuel=1,jokerUpgradeTotalAmmoBag=1,jokerSpareBullets=1},'itemJetpack')
    near(a.magazine,8)
    near(a.reserve,9)
    near(a.startingMagazine,9)
end)
test('CrashPack doubles the already combined Jetpack reserve once regardless of its copy count',function()
    local a=ammo({jokerUpgradeJetpackFuel=1,jokerUpgradeTotalAmmoBag=1,jokerSpareBullets=1,jokerCrashPack=4},'itemJetpack')
    near(a.magazine,18)
    near(a.reserve,18)
    near(a.startingMagazine,18)
end)
test('DrawSpeed sums with QuickDraw and divides delay rather than subtracting a percentage',function()
    local p=E.preview('jokerUpgradeDrawSpeed',{jokerUpgradeDrawSpeed=1},
        {itemName='itemPistol',itemCounts={jokerQuickDraw=1},baseSwapDelay=1.2})
    near(val(p.current,'swapSpeedBonus'),.3)
    near(val(p.current,'swapDelayMultiplier'),1/1.7)
    near(val(p.after,'swapDelayMultiplier'),.5)
    near(val(p.after,'swapDelay'),.6)
end)
test('Jetpack force recalculates at activation and does not pretend its force term is final velocity',function()
    local p=E.preview('jokerUpgradeJetpackForce',{jokerUpgradeJetpackForce=1},{jetpackElevationForce=512})
    near(val(p.current,'elevationForce'),315)
    near(val(p.after,'elevationForce'),330)
    near(val(p.current,'storedElevationForce'),512)
    near(val(p.after,'storedElevationForce'),512)
    near(val(E.evaluate('jokerUpgradeJetpackForce',300,{}),'elevationForce'),4800)
end)
test('Jetpack duration uses its one-second timeline with CrashPack presence and preserves unknown context',function()
    local p=E.preview('jokerUpgradeJetpackFlightDuration',{jokerUpgradeJetpackFlightDuration=1},{itemCounts={}})
    near(val(p.current,'flightDuration'),2.1)
    near(val(p.after,'flightDuration'),2.2)
