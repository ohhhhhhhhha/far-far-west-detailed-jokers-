test('ChargingSpeed increases charge awarded per qualifying hit for both actual applicable weapons',function()
    for _,item in ipairs({'itemKnuckles','itemLasso'}) do
        local p=E.preview('jokerUpgradeChargingSpeed',{jokerUpgradeChargingSpeed=1},{itemName=item})
        near(val(p.current,'chargeGain'),.107525)
        near(val(p.after,'chargeGain'),.12155)
    end
    near(val(E.evaluate('jokerUpgradeChargingSpeed',20,{itemName='itemKnuckles'}),'chargeGain'),.374)
end)
test('Chord capacity is cached on draw and candidate levels do not rewrite that cache',function()
    local p=E.preview('jokerUpgradeChordCapacity',{jokerUpgradeChordCapacity=1},
        {banjoAdditionalChords=0,itemCounts={}})
    near(val(p.current,'currentChordCapacity'),7)
    near(val(p.after,'currentChordCapacity'),7)
    near(val(p.current,'nextDrawChordCapacity'),8)
    near(val(p.after,'nextDrawChordCapacity'),9)
end)
test('Chord upgrades also multiply special damage but honor the empty Bardbarian cache branch',function()
    near(val(E.evaluate('jokerUpgradeChordCapacity',2,{itemCounts={}}),'specialAttackDamage'),32.5)
    near(val(E.evaluate('jokerUpgradeChordCapacity',2,{itemCounts={jokerBardbarian=1},bardbarianStoredDamage=100}),'specialAttackDamage'),130)
    near(val(E.evaluate('jokerUpgradeChordCapacity',2,{itemCounts={jokerBardbarian=1},bardbarianStoredDamage=0}),'specialAttackDamage'),25)
    eq(val(E.evaluate('jokerUpgradeChordCapacity',2,{itemCounts={jokerBardbarian=1}}),'specialAttackDamage'),nil)
end)
test('all upgrade-prefix rows have a verified consumer or explicit verified inapplicability',function()
    for _,c in ipairs(C.all()) do
        if c.id:lower():find('jokerupgrade',1,true) then
            local r=E.rule(c.id);eq(r and r.status,'verified',c.id)
        end
    end
end)
print(('joker_upgrade_completion_test: %d cases, %d assertions, %d failures'):format(cases,checks,failed))
assert(failed==0,'joker_upgrade_completion_test failed')
