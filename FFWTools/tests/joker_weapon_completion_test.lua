package.path='FFWTools/src/FFWJokerInfo/Scripts/?.lua;'..package.path
local Effects,Cards=require('Effects'),require('Cards')
local cases,checks,failed=0,0,0
local function eq(a,b,why) checks=checks+1;assert(a==b,(why or '')..' expected '..tostring(b)..', got '..tostring(a)) end
local function near(a,b,why) checks=checks+1;assert(type(a)=='number' and math.abs(a-b)<1e-6,(why or '')..' expected '..b..', got '..tostring(a)) end
local function evaluate(id,n,i) return Effects.evaluate('joker'..id,n,i or {}) end
local function value(r,k) assert(r.metrics[k],'missing metric '..k);return r.metrics[k].value end
local function test(name,fn) cases=cases+1;local ok,err=pcall(fn);if ok then print('PASS '..name) else failed=failed+1;print('FAIL '..name..': '..err) end end

test('Destroyer reads the impact-time magazine with the inclusive three-quarter boundary',function()
    near(value(evaluate('Destroyer',2,{itemName='itemPistol',magazineAmmo=6,magazineMaximum=8}),'damageBonus'),.4)
    near(value(evaluate('Destroyer',2,{itemName='itemPistol',magazineAmmo=5,magazineMaximum=8}),'damageBonus'),0)
    eq(value(evaluate('Destroyer',2,{itemName='itemPistol'}),'damageBonus'),nil)
    near(value(evaluate('Destroyer',2,{itemName='itemMinigun',ammoCurrent=75,ammoMaximum=100}),'damageBonus'),.4)
end)
test('Execute uses the enemy estimated damage threshold and excludes elite and boss targets',function()
    near(value(evaluate('Execute',1),'remainingHealthThreshold'),.2)
    near(value(evaluate('Execute',2),'remainingHealthThreshold'),.3)
    near(value(evaluate('Execute',8),'remainingHealthThreshold'),.35)
    local i={targetIsEnemy=true,targetIsBoss=false,targetIsElite=false,targetDefaultHealth=100,targetEstimatedDamage=70}
    eq(value(evaluate('Execute',2,i),'executeEligible'),true)
    near(value(evaluate('Execute',2,i),'executionDamage'),31)
    i.targetIsElite=true;eq(value(evaluate('Execute',2,i),'executeEligible'),false)
end)
