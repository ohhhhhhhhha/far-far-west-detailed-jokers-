    for _,id in ipairs({'Destroyer','CanOpenener','Execute','AimingBurst','HomingBurst','OverBlast','RushBlast','FocusShot','ElementalSpin','MarkAce','OverDraw','UltraDraw','EcoTrick','SwampTrick','JumpStar','ScavengerStar','StackedLever','ChonkyThrow','LingeringThrow','FistRoDah','FistRage','SkyLash','SpellLash','Lullabard','Bardbarian','TrailPack','CrashPack','HoverPack','Speedster'}) do
        local p=Effects.preview('joker'..id,{['joker'..id]=1},{})
        eq(p.scope,'item');eq(p.status,id=='CanOpenener' and 'disabled' or 'verified');eq(p.lines[2],Cards.get('joker'..id).description)
        eq(p.runtimeVerified,false)
    end
    for _,id in ipairs({'Destroyer','Execute','Speedster','HomingBurst','RushBlast','OverDraw','FistRage','SkyLash','Bardbarian','CrashPack'}) do
        eq(evaluate(id,1).complete,false,id)
    end
end)

