test('selection previews keep existing weapon caches and resource readings unchanged',function()
    for _,case in ipairs({
        {'jokerFistRage',{itemCounts={},fistRageActive=false,knucklesCharge=.4},'attackSpeedBonus',0},
        {'jokerSpellLash',{lassoCharge=.25},'currentCharge',.25},
        {'jokerCrashPack',{itemCounts={},ammoCurrent=3},'currentFuel',3},
        {'jokerSkyLash',{skyLashBuffSpeed=500},'currentBuffSpeed',500},
        {'jokerBardbarian',{itemCounts={},bardbarianStoredDamage=42},'currentSpecialBaseDamage',42},
    }) do
        local id,i,k,v=table.unpack(case)
        local p=Effects.preview(id,{[id]=1},i)
        near(value(p.current,k),v);near(value(p.after,k),v)
        eq(p.runtimeVerified,false)
    end
end)

