package.path='FFWTools/src/FFWJokerInfo/Scripts/?.lua;'..package.path
local I=require('Inventory')
local P=require('Panel')
local C=require('Cards')
local checks=0
local function eq(a,b,m) checks=checks+1; assert(a==b,(m or '')..' expected '..tostring(b)..', got '..tostring(a)) end
local s=I.fromSnapshot({selected={primary='itemQuadCylinder',secondary='itemKnuckles'},equipped={itemQuadCylinder={'jokerCrackShot'},itemHero={'jokerWellFed'}},upgrades={},runtime={'jokerCrackShot'}})
local es=P.entries(s)
eq(#es,3,'one entry per applicable item/card')
eq(es[1].card.id,'jokerWellFed','hero section precedes weapon sections')
local description=P.description('jokerCrackShot',s,'itemQuadCylinder','equip','原始描述')
eq(description:sub(1,#'原始描述'),'原始描述')
eq(description:find('当前 2 张',1,true),nil)
eq(description:find('+14%',1,true)~=nil,true)
eq(description:find('+21%',1,true)~=nil,true)
eq(description:find('大厅',1,true),nil)
eq(description:find('F7',1,true),nil)
local once=P.description('jokerCrackShot',s,'itemQuadCylinder','equip',description)
eq(once,description,'repeated UI refresh must not duplicate appended text')
local all=P.description('jokerCrackShot',s,nil,'pickup')
eq(all:find('主武器',1,true)~=nil,true)
eq(all:find('副武器',1,true)~=nil,true)
eq(all:find('角色',1,true),nil,'global task pickup only previews eligible items')
local bad=I.fromSnapshot({selected=s.selected,equipped=s.equipped,runtime=s.runtime})
local unavailable=P.description('jokerCrackShot',bad,'itemQuadCylinder','equip')
eq(unavailable:find('效果待读取',1,true)~=nil,true)
eq(unavailable:find('+14%',1,true),nil,'partial inventory must not display partial contribution as total')
local page=P.page(s,1)
eq(page.index,1)
eq(page.count,3)
eq(page.detail:find(C.get('jokerWellFed').description,1,true)~=nil,true)
eq(page.detail:find('选取后',1,true),nil,'current menu must not imply candidate is being selected')
eq(P.page(s,100).index,3)
eq(P.page(s,-1).index,1)
local empty=P.page(I.fromSnapshot({selected=s.selected,equipped={},upgrades={},runtime={}}),1)
eq(empty.count,0)
eq(empty.detail:find('没有',1,true)~=nil,true)
local capped=I.fromSnapshot({selected={primary='itemLongRanger'},equipped={itemHero={'jokerLightWeight','jokerLightWeight'}},upgrades={},runtime={},
    inputs={heldItemName='itemLongRanger',buffGravity=0}})
local capText=P.description('jokerLightWeight',capped,'itemHero','equip')
eq(capText:find('无加成',1,true)~=nil,true)
eq(capText:find('装备后 3 张',1,true),nil,'unavailable equip action must not be presented as an available candidate')
eq(P.description('jokerLightWeight',capped,'itemHero','pickup'):find('1.15 → 1.1',1,true)~=nil,true,'hall limit does not cap task pickup')
print('joker_panel_test: '..checks..' checks passed')
