package.path='FFWTools/src/FFWJokerInfo/Scripts/?.lua;'..package.path
local Effects=require('Effects')
local checks,tests,failures=0,0,0
local function eq(a,b) checks=checks+1;assert(a==b,'expected '..tostring(b)..', got '..tostring(a)) end
local function near(a,b) checks=checks+1;assert(type(a)=='number' and math.abs(a-b)<1e-6,'expected '..tostring(b)..', got '..tostring(a)) end
local function m(id,n,inputs,key) local r=Effects.evaluate(id,n,inputs);assert(r.metrics[key],'missing '..id..'.'..key);return r.metrics[key] end
local function v(id,n,inputs,key) return m(id,n,inputs,key).value end
local function test(name,fn) tests=tests+1;local ok,err=pcall(fn);if ok then print('PASS '..name) else failures=failures+1;print('FAIL '..name..': '..tostring(err)) end end

-- Hand-derived expectations from complete CUE bytecode, indexed in joker-hero-completion.md.
test('ghost strength and revive channel consume cumulative values directly',function()
    near(v('jokerDeadlyStrong',2,{},'ghostSpeed'),3000)
    near(v('jokerDeadlyStrong',2,{},'ghostDamage'),30)
    near(v('jokerHelpingHand',2,{},'reviveTime'),.75)
    near(v('jokerHelpingHand',0,{},'reviveTime'),3)
    near(v('jokerHelpingHand',8,{},'interactionDelay'),.5)
end)
