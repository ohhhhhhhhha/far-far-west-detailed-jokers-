package.path='FFWTools/src/FFWJokerInfo/Scripts/?.lua;'..package.path
local Effects,Cards=require('Effects'),require('Cards')
local cases,checks,failed=0,0,0
local function eq(a,b,message)
    checks=checks+1;assert(a==b,(message or '')..' expected '..tostring(b)..', got '..tostring(a))
end
local function near(a,b,message)
    checks=checks+1;assert(type(a)=='number' and math.abs(a-b)<1e-6,
        (message or '')..' expected '..tostring(b)..', got '..tostring(a))
end
local function val(result,key)
    assert(result.metrics[key],'missing reactive metric '..key)
    return result.metrics[key].value
end
local function test(name,fn)
    cases=cases+1;local ok,err=pcall(fn)
    if ok then print('PASS '..name) else failed=failed+1;print('FAIL '..name..': '..tostring(err)) end
end
local function hitInputs(extra)
    local i={hitMeActive=true,hitMeCachedValue=2,health=90,maxHealth=100,
        droughtActive=false,healingThickSkinCount=0,healingTargetIsGhost=false}
    for k,v in pairs(extra or {}) do i[k]=v end
    return i
end

-- Literal expectations come from the two trigger/cache/consumer paths in retained UE bytecode.
test('HitMe scales its next raw pulse while its refresh duration stays twenty seconds',function()
    local p=Effects.preview('jokerHitMe',{jokerHitMe=1},{})
    near(val(p.current,'nextTriggerHealPerSecond'),.75)
    near(val(p.after,'nextTriggerHealPerSecond'),1.5)
    near(val(p.current,'triggerDuration'),20)
    near(val(p.after,'triggerDuration'),20)
    eq(p.equipLimit,1)
    local many=Effects.evaluate('jokerHitMe',8,{})
    near(val(many,'nextTriggerHealPerSecond'),6)
    near(val(many,'triggerDuration'),20)
end)
test('HitMe candidate counts do not rewrite the current timer cache',function()
    local i=hitInputs({hitMeCachedValue=1})
    local p=Effects.preview('jokerHitMe',{jokerHitMe=1},i)
    near(val(p.current,'currentHealPerSecond'),.75)
    near(val(p.after,'currentHealPerSecond'),.75)
    near(val(p.after,'nextTriggerHealPerSecond'),1.5)
    eq(i.hitMeCachedValue,1)
    near(val(Effects.evaluate('jokerHitMe',7,hitInputs()),'currentHealPerSecond'),1.5)
end)
test('HitMe requires observed active state and cache instead of substituting held card count',function()
    local r=Effects.evaluate('jokerHitMe',4,{hitMeActive=true})
    eq(val(r,'currentHealPerSecond'),nil)
    eq(r.complete,false)
    r=Effects.evaluate('jokerHitMe',4,{hitMeCachedValue=2})
    eq(val(r,'currentHealPerSecond'),nil)
    r=Effects.evaluate('jokerHitMe',4,{hitMeActive=false})
    near(val(r,'currentHealPerSecond'),0)
    near(val(r,'effectiveHealNextTick'),0)
end)
test('HitMe uses cached zero and can retain a running cache until the next actual check',function()
    near(val(Effects.evaluate('jokerHitMe',8,hitInputs({hitMeCachedValue=0})),'currentHealPerSecond'),0)
    local r=Effects.evaluate('jokerHitMe',0,hitInputs())
    near(val(r,'currentHealPerSecond'),1.5,'the timer consumer does not recheck card possession')
    near(val(r,'nextTriggerHealPerSecond'),0)
    eq(val(r,'triggerDuration'),nil)
    eq(r.metrics.totalHeal,nil,'timer restart and concurrent healing prevent a fixed total')
end)
test('HitMe accepts an explicitly observed after cache without mutating its input',function()
    local i=hitInputs({hitMeCachedValue=1,after={hitMeCachedValue=2}})
    local p=Effects.preview('jokerHitMe',{jokerHitMe=1},i)
    near(val(p.current,'currentHealPerSecond'),.75)
    near(val(p.after,'currentHealPerSecond'),1.5)
    eq(i.hitMeCachedValue,1)
end)
test('HitMe applies drought and actual ThickSkin healing count before the health cap',function()
    local i=hitInputs({droughtActive=true,healingThickSkinCount=2})
    near(val(Effects.evaluate('jokerHitMe',2,i),'currentHealPerSecond'),1.5)
    near(val(Effects.evaluate('jokerHitMe',2,i),'effectiveHealNextTick'),.45)
    i.health=99.8
    near(val(Effects.evaluate('jokerHitMe',2,i),'effectiveHealNextTick'),.2)
    i.health=100
    near(val(Effects.evaluate('jokerHitMe',2,i),'effectiveHealNextTick'),0)
end)
test('HitMe never counts TinMan overflow as positive health recovery',function()
    local i=hitInputs({health=99.5})
    local r=Effects.evaluate('jokerHitMe',2,i)
    near(val(r,'effectiveHealNextTick'),.5)
    i.health=100
    near(val(Effects.evaluate('jokerHitMe',2,i),'effectiveHealNextTick'),0)
end)
test('HitMe unknown healing modifiers stay unknown and a ghost has no positive health recovery',function()
    for _,missing in ipairs({'droughtActive','healingThickSkinCount','healingTargetIsGhost','health','maxHealth'}) do
        local i=hitInputs();i[missing]=nil
        eq(val(Effects.evaluate('jokerHitMe',2,i),'effectiveHealNextTick'),nil,missing)
    end
    near(val(Effects.evaluate('jokerHitMe',2,hitInputs({healingTargetIsGhost=true,health=0})),'effectiveHealNextTick'),0)
end)
test('FightOrFlight scales the next saved bonus and refresh duration with card count',function()
    local p=Effects.preview('jokerFightOrFlight',{jokerFightOrFlight=1},{fightOrFlightValue=.2})
    near(val(p.current,'nextTriggerAttackSpeedBonus'),.2)
    near(val(p.after,'nextTriggerAttackSpeedBonus'),.4)
    near(val(p.current,'triggerDuration'),3)
    near(val(p.after,'triggerDuration'),6)
    eq(p.equipLimit,2)
    local many=Effects.evaluate('jokerFightOrFlight',7,{fightOrFlightValue=0})
    near(val(many,'nextTriggerAttackSpeedBonus'),1.4)
    near(val(many,'triggerDuration'),21)
end)
test('FightOrFlight reads its current stored additive bonus without multiplying it again',function()
    local i={fightOrFlightValue=.2}
    local p=Effects.preview('jokerFightOrFlight',{jokerFightOrFlight=3},i)
    near(val(p.current,'attackSpeedBonus'),.2)
    near(val(p.after,'attackSpeedBonus'),.2)
    near(val(p.after,'nextTriggerAttackSpeedBonus'),.8)
    eq(i.fightOrFlightValue,.2)
end)
test('FightOrFlight expired or missing cache cannot become an active buff from acquisition',function()
    local p=Effects.preview('jokerFightOrFlight',{jokerFightOrFlight=1},{fightOrFlightValue=0})
    near(val(p.current,'attackSpeedBonus'),0)
    near(val(p.after,'attackSpeedBonus'),0)
    local r=Effects.evaluate('jokerFightOrFlight',2,{})
    eq(val(r,'attackSpeedBonus'),nil)
    eq(r.complete,false)
    r=Effects.evaluate('jokerFightOrFlight',0,{fightOrFlightValue=.6})
    near(val(r,'attackSpeedBonus'),0,'the weapon consumer requires possession')
    eq(val(r,'triggerDuration'),nil)
end)
test('FightOrFlight uses a newly observed after cache only when supplied',function()
    local p=Effects.preview('jokerFightOrFlight',{jokerFightOrFlight=1},
        {fightOrFlightValue=.2,after={fightOrFlightValue=.4}})
    near(val(p.current,'attackSpeedBonus'),.2)
    near(val(p.after,'attackSpeedBonus'),.4)
end)
test('reactive cards preserve Chinese text and report static hero rules',function()
    for _,id in ipairs({'jokerHitMe','jokerFightOrFlight'}) do
        local p=Effects.preview(id,{[id]=1},{})
        eq(p.status,'verified')
        eq(p.scope,'hero')
        eq(p.lines[2],Cards.get(id).description)
        eq(p.runtimeVerified,false)
    end
end)
print(('joker_reactive_cards_test: %d cases, %d assertions, %d failures'):format(cases,checks,failed))
assert(failed==0,'joker_reactive_cards_test failed')
